FREE_CATALOG = [b for b in CATALOG if not b["premium"]]
PREMIUM_CATALOG = [b for b in CATALOG if b["premium"]]


def find_book(book_id: int) -> dict | None:
    return next((b for b in CATALOG if b["id"] == book_id), None)


def search_books(query: str) -> list[dict]:
    q = query.lower().strip()
    if not q:
        return []
    return [
        b for b in CATALOG
        if q in b["title"].lower()
        or q in b["author"].lower()
        or q in b["genre"].lower()
    ]
